import type { PlanningPoint } from "@/api/planning"

interface ApplicabilityProps {
  points: readonly PlanningPoint[]
  route: string
}

const percent = (share: number) => `${Math.round(share * 100)}%`

function allocatedShare(points: readonly PlanningPoint[]): number | null {
  const total = points.reduce((sum, point) => sum + point.route_scenario, 0)
  if (!(total > 0)) return null
  return 1 - points.reduce((sum, point) => sum + point.route_unallocated_scenario, 0) / total
}

export function Applicability({ points, route }: ApplicabilityProps) {
  const share = allocatedShare(points)
  return <section className="planning-applicability" aria-label="Область применимости модели">
    <h3>Область применимости модели</h3>
    <dl>
      <div><dt>Маршруты</dt><dd>1, 7, 11, 12, 17, 25, 26, 28, 50 — прогноз по остановкам. Маршрут 5 — только маршрутный итог: в истории нет ни одной успешной валидации.</dd></div>
      <div><dt>Данные и период</dt><dd>Обучение на валидациях 01.01–31.10.2025, прогноз на 01.11–31.12.2025. Шаг — час, время московское.</dd></div>
      <div><dt>Горизонты</dt><dd>День (по часам) и месяц (по дням) проверены на трёх 61-дневных окнах — май, июль, сентябрь: 1 − WAPE маршрутной модели 0,84–0,89, на публичном лидерборде 0,892. Год — качественная проекция: повтор профиля «день недели × час», годовая сезонность не обучена.</dd></div>
      <div><dt>Что прогнозируется</dt><dd>Число успешных валидаций (посадок). Это не наполненность вагона и не уникальные пассажиры; высадок и вместимости в данных нет. Интервалов неопределённости нет — только точечный прогноз.</dd></div>
      <div><dt>Остановки</dt><dd>По остановкам распределено около 78% посадок ноября–декабря{share === null ? "" : `, по маршруту ${route} в выбранном периоде — ${percent(share)}`}. Привязка выведена из расписания (первая валидация рейса — первая остановка), проверенной истины по остановкам нет.</dd></div>
      <div><dt>Направления</dt><dd>Оценка по расписанию, не наблюдение: по данным валидаций направление движения не определяется.</dd></div>
      <div><dt>Внешние факторы</dt><dd>Календарь встроен в модель. Погода, трафик и новости проверены отдельно — устойчивого прироста на всех окнах нет, поэтому их влияние задаётся весами отдельных сценарных моделей.</dd></div>
      <div><dt>Перенос на новые маршруты и периоды</dt><dd>Нужны история валидаций маршрута, его GTFS-каталог остановок и повторная хронологическая проверка на 61-дневных окнах до даты отсечки данных.</dd></div>
    </dl>
  </section>
}
